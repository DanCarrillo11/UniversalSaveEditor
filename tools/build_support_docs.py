"""Keep coverage documentation aligned with the evidence shown by the app."""
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from catalog import GAMES
from compatibility import EVIDENCE,coverage_label,evidence_label
from support_matrix import GAPS


def documents():
    if {g.id for g in GAMES}!=set(GAPS) or set(GAPS)!=set(EVIDENCE):
        raise ValueError('Every current game needs evidence and an explicit remaining-gate entry.')
    coverage='# Editor coverage and previews\n\n'
    coverage+='Generated by `tools/build_support_docs.py` from the same evidence used in the app.\n'
    coverage+='No editor is currently classified as full support. Feature coverage, native-file\nchecks and in-game verification are separate. Field counts are not percentages.\n\n'
    coverage+='| Game | Coverage | File evidence | Current supported scope |\n| --- | --- | --- | --- |\n'
    for game in GAMES:
        coverage+=f'| {game.title} | {coverage_label(game.id)} | {evidence_label(game.id)} | {EVIDENCE[game.id].limits} |\n'
    coverage+='\n## No-save browsing\n\nClick a game with no available save to browse a read-only example. The banner\n'
    coverage+='says **No save data found**. Example values are not a real save. Open a save\n'
    coverage+='to edit; previews never write files or enter recent-file history. Available\n'
    coverage+='fields depend on the file, revision and selected slot. Gameplay and system\n'
    coverage+='profiles can expose different tools. `assets/editor-previews.json` is generated\n'
    coverage+='from synthetic adapter fixtures, with no personal saves or writable offsets.\n'
    plan='# Complete the current catalogue before adding games\n\n'
    plan+=f'All {len(GAMES)} current editors remain in scope. New games and original icon work\n'
    plan+='are deferred while functionality is completed. Resident Evil, starting with\nRequiem, has priority. No editor is currently marked full support.\n\n'
    plan+='Generated by `tools/build_support_docs.py`; pending gates come from\n`support_matrix.py`, and the app uses `compatibility.py` for current evidence.\n\n'
    plan+='| Game | Remaining functional gates |\n| --- | --- |\n'
    for game in GAMES:plan+=f'| {game.title} | {GAPS[game.id]} |\n'
    plan+='\n## Completion criteria\n\nEach agreed operation needs identified data, correct bounds, dependent-state\n'
    plan+='handling, preservation of unrelated bytes, round-trip checks and in-game\n'
    plan+='verification where behavior depends on the engine. A visible preview or a\n'
    plan+='passing file checksum does not establish successful game loading or reward\n'
    plan+='delivery. Unsupported revisions and unknown encodings remain protected.\n\n'
    plan+='See [current coverage](EDITOR_COVERAGE.md), [implementation evidence](CURRENT_GAME_COMPLETION.md)\n'
    plan+='and [original artwork coverage](ITEM_ARTWORK.md). RE0 is research-only.\n'
    return {'docs/EDITOR_COVERAGE.md':coverage,'docs/COMPLETION_PLAN.md':plan}


if __name__=='__main__':
    for path,text in documents().items():(ROOT/path).write_text(text,encoding='utf-8',newline='\n')
    print(f'Regenerated evidence and remaining gates for {len(GAMES)} editors.')
