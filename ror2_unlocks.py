def _words(value):
    """Make internal camel-case names readable without changing their identifier."""
    import re
    value = value.replace('_', ' ').replace('-', ' ')
    return re.sub(r'(?<=[a-z0-9])(?=[A-Z])', ' ', value).strip()

def unlock_group(identifier):
    return GROUPS[identifier.split('.', 1)[0]]

def unlock_label(identifier):
    parts = identifier.split('.')
    category, tail = parts[0], parts[1:]
    if category == 'Characters':
        return NAMES.get(tail[0], _words(tail[0]))
    if category in ('Skills', 'Skins') and len(tail) > 1:
        owner = NAMES.get(tail[0], _words(tail[0]))
        detail = ' · '.join(_words(value) for value in tail[1:])
        return f'{owner} · {detail}'
    if category == 'NewtStatue':
        return ' · '.join(('Altar',) + tuple(_words(value) for value in tail))
    return ' · '.join(_words(value) for value in tail)
